#!/usr/bin/env node
// Writes dist/index.js, the file .kiro/settings/mcp.json starts. It is a one-line entry that loads src/stdio.mjs, so the server
// runs from the same source the tests cover. Run after any change here: node tools/worldlabs-mcp/build.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, 'dist', 'index.js');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(resolve(here, 'dist', 'package.json'), JSON.stringify({ type: 'module' }, null, 2) + '\n');
writeFileSync(out, "#!/usr/bin/env node\n// Generated by tools/worldlabs-mcp/build.mjs. Edit src/, not this file.\nimport '../src/stdio.mjs';\n");
console.log(`wrote ${out}`);
