// Shared by tools/build-banks.mjs and tools/check-voice-library.mjs.
// The story markdown in docs/story/ is the place a person edits. The typed banks in shared/src/voice/banks/ are generated from it.

/** Kinds that are shown but never spoken, so never rendered (party-mode 7.8: the Lodger aside is text only). */
export const TEXT_ONLY_KINDS = new Set(['aside']);

/**
 * Parse the rows of docs/story/lodger-lines.md: | `lodger.<kind>.<n>` | line |
 * A writer may add a note to a cell: `line. REVIEW: reason`. The note is never part of the line, so it is split off
 * and kept in `review` (it is not written to the generated bank and is never rendered or spoken).
 * @param {string} markdown
 * @returns {{ id: string, kind: string, text: string, spoken: boolean, review: string | null }[]}
 */
export function parseLodgerLines(markdown) {
  const rows = [];
  const re = /^\|\s*`(lodger\.(aside|stall|confession)\.(\d+))`\s*\|\s*(.+?)\s*\|\s*$/gm;
  for (const m of markdown.matchAll(re)) {
    const [, id, kind, , cell] = m;
    const [text, ...note] = cell.split(/\s+REVIEW:\s*/);
    rows.push({ id, kind, text: text.trim(), spoken: !TEXT_ONLY_KINDS.has(kind), review: note.length ? note.join(' REVIEW: ') : null });
  }
  return rows;
}

/**
 * The text of shared/src/voice/banks/lodger.ts for these lines.
 * @param {{ id: string, kind: string, text: string, spoken: boolean }[]} lines
 */
export function renderLodgerBankTs(lines) {
  const body = lines
    .map((l) => `  { id: ${JSON.stringify(l.id)}, kind: ${JSON.stringify(l.kind)}, text: ${JSON.stringify(l.text)}, spoken: ${l.spoken} },`)
    .join('\n');
  return `// GENERATED by tools/build-banks.mjs from docs/story/lodger-lines.md. Do not edit by hand: edit the markdown, then run
// \`node tools/build-banks.mjs\`. \`node tools/check-voice-library.mjs\` fails when this file is out of date.
import type { BankLine } from "../library";

/** The Lodger bank, shared by all six Suspects. \`spoken: false\` (the aside) is text only and is never rendered. */
export const LODGER_BANK: readonly BankLine[] = [
${body}
];
`;
}

// ---- The Whisper and the Keeper: docs/story/ghost-lines.md (single player) and docs/story/party-lines.md (party) ----

/** `soft` is the Whisper's id suffix, `dry` the Keeper's (the two Creator voices, docs/story/VOICE.md). */
export const SPEAKER_OF_SUFFIX = { soft: 'whisper', dry: 'keeper' };
const SUFFIX_OF_HEADING = [[/\bWhisper\b/, 'soft'], [/\bKeeper\b/, 'dry']];

/**
 * Parse the rows of a Whisper and Keeper bank: | `<kind>.<soft|dry>.<n>` | line |
 * Whether a line is spoken comes from the heading above its table: a heading that says "text only" means the lines are shown and
 * never spoken or rendered; any other heading means spoken. `headingSuffix` is the voice the heading names ("the Whisper",
 * "Keeper: ..."), so a line under the wrong voice can be caught. A `REVIEW:` note is split off, as for the Lodger.
 * @param {string} markdown
 * @returns {{ id: string, kind: string, speaker: 'whisper' | 'keeper', suffix: 'soft' | 'dry', text: string, spoken: boolean, review: string | null, headingSuffix: 'soft' | 'dry' | null }[]}
 */
export function parseSpeakerLines(markdown) {
  const rows = [];
  let spoken = true;
  let headingSuffix = null;
  const row = /^\|\s*`([a-z][a-z0-9-]*(?:\.[a-z][a-z0-9-]*)*)\.(soft|dry)\.(\d+)`\s*\|\s*(.+?)\s*\|\s*$/;
  for (const line of markdown.split('\n')) {
    if (/^#{1,6}\s/.test(line)) {
      spoken = !/text only/i.test(line);
      headingSuffix = SUFFIX_OF_HEADING.find(([re]) => re.test(line))?.[1] ?? null;
      continue;
    }
    const m = row.exec(line);
    if (!m) continue;
    const [, kind, suffix, n, cell] = m;
    const [text, ...note] = cell.split(/\s+REVIEW:\s*/);
    rows.push({ id: `${kind}.${suffix}.${n}`, kind, speaker: SPEAKER_OF_SUFFIX[suffix], suffix, text: text.trim(), spoken, review: note.length ? note.join(' REVIEW: ') : null, headingSuffix });
  }
  return rows;
}

/**
 * The text of a generated Whisper and Keeper bank file.
 * @param {{ id: string, kind: string, speaker: string, text: string, spoken: boolean }[]} lines
 * @param {{ source: string, prefix: string, what: string }} o  prefix is the export prefix, e.g. GHOST
 */
export function renderSpeakerBanksTs(lines, { source, prefix, what }) {
  const bank = (speaker) => lines
    .filter((l) => l.speaker === speaker)
    .map((l) => `  { id: ${JSON.stringify(l.id)}, kind: ${JSON.stringify(l.kind)}, text: ${JSON.stringify(l.text)}, spoken: ${l.spoken} },`)
    .join('\n');
  return `// GENERATED by tools/build-banks.mjs from ${source}. Do not edit by hand: edit the markdown, then run
// \`node tools/build-banks.mjs\`. \`node tools/check-voice-library.mjs\` fails when this file is out of date.
import type { BankLine } from "../library";

/** The Whisper's lines (id suffix \`soft\`): ${what}. \`spoken: false\` is text only and is never rendered. */
export const ${prefix}_WHISPER_BANK: readonly BankLine[] = [
${bank('whisper')}
];

/** The Keeper's lines (id suffix \`dry\`): ${what}. \`spoken: false\` is text only and is never rendered. */
export const ${prefix}_KEEPER_BANK: readonly BankLine[] = [
${bank('keeper')}
];
`;
}

/** The two Whisper and Keeper banks: where each is written and generated. One list, used by build-banks.mjs and check-voice-library.mjs. */
export const SPEAKER_BANK_TARGETS = [
  { source: 'docs/story/ghost-lines.md', out: 'shared/src/voice/banks/ghost.ts', prefix: 'GHOST', what: 'single player' },
  { source: 'docs/story/party-lines.md', out: 'shared/src/voice/banks/party.ts', prefix: 'PARTY', what: 'party mode' },
];

/** The generated TypeScript for one target, from its markdown. */
export const renderSpeakerTarget = (target, markdown) =>
  renderSpeakerBanksTs(parseSpeakerLines(markdown), { source: target.source, prefix: target.prefix, what: target.what });
