// Shared by tools/build-banks.mjs and tools/check-voice-library.mjs.
// The story markdown in docs/story/ is the place a person edits. The typed banks in shared/src/voice/banks/ are generated from it.

/** Kinds that are shown but never spoken, so never rendered (party-mode 7.8: the Lodger aside is text only). */
export const TEXT_ONLY_KINDS = new Set(['aside']);

/**
 * Parse the rows of docs/story/lodger-lines.md: | `lodger.<kind>.<n>` | line |
 * A writer may add a note to a cell: `line. REVIEW: reason`. The note is never part of the line, so it is split off
 * and kept in `review` (it is not written to the generated bank and is never rendered or spoken).
 * @param {string} markdown
 * @returns {{ id: string, kind: string, text: string, spoken: boolean, review: string | null }[]}
 */
export function parseLodgerLines(markdown) {
  const rows = [];
  const re = /^\|\s*`(lodger\.(aside|stall|confession)\.(\d+))`\s*\|\s*(.+?)\s*\|\s*$/gm;
  for (const m of markdown.matchAll(re)) {
    const [, id, kind, , cell] = m;
    const [text, ...note] = cell.split(/\s+REVIEW:\s*/);
    rows.push({ id, kind, text: text.trim(), spoken: !TEXT_ONLY_KINDS.has(kind), review: note.length ? note.join(' REVIEW: ') : null });
  }
  return rows;
}

/**
 * The text of shared/src/voice/banks/lodger.ts for these lines.
 * @param {{ id: string, kind: string, text: string, spoken: boolean }[]} lines
 */
export function renderLodgerBankTs(lines) {
  const body = lines
    .map((l) => `  { id: ${JSON.stringify(l.id)}, kind: ${JSON.stringify(l.kind)}, text: ${JSON.stringify(l.text)}, spoken: ${l.spoken} },`)
    .join('\n');
  return `// GENERATED by tools/build-banks.mjs from docs/story/lodger-lines.md. Do not edit by hand: edit the markdown, then run
// \`node tools/build-banks.mjs\`. \`node tools/check-voice-library.mjs\` fails when this file is out of date.
import type { BankLine } from "../library";

/** The Lodger bank, shared by all six Suspects. \`spoken: false\` (the aside) is text only and is never rendered. */
export const LODGER_BANK: readonly BankLine[] = [
${body}
];
`;
}
